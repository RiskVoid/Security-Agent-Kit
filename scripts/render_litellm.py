"""Render the LiteLLM config the container reads (.rvkit/litellm.yaml) from the tracked template
(litellm/config.yaml) and the user's settings in .env. Run by ./rvkit before LiteLLM starts.

Settings (.env):
  OPENROUTER_DAILY_BUDGET   USD per day for all OpenRouter calls (planner, and the worker fallback when on). Default 20
  WORKER_FALLBACK           on | off (default off). on: while the worker endpoint is down, worker calls go to
                            WORKER_FALLBACK_MODEL on OpenRouter, which then sees tool output and client code
  PLANNER_MODEL, PLANNER_FALLBACK_MODEL, VALIDATOR_MODEL
                            openrouter/<id> (default): OpenRouter key, zero-data-retention providers only.
                            anthropic/<id> or openai/<id>: that provider's API directly, with ANTHROPIC_API_KEY or
                            OPENAI_API_KEY. The daily budget then also caps that provider (Anthropic: provider budget;
                            OpenAI: a budget on each planner model, because the worker also counts as provider "openai").
                            bedrock/<id>: Amazon Bedrock (AWS credits pay for it) with the Bedrock API key in
                            AWS_BEARER_TOKEN_BEDROCK and the region in AWS_REGION_NAME; the daily budget caps it too.
  WORKER_MODEL_ID           openai/<name> (default): the OpenAI-compatible endpoint at WORKER_API_BASE (Colab, a local
                            server, RunPod, ...). openrouter/<id> (./rvkit worker openrouter): a hosted model, no GPU
                            needed; it uses OPENROUTER_API_KEY, zero-data-retention providers and the OpenRouter budget.
                            bedrock/<id> (./rvkit worker bedrock): a model on Amazon Bedrock, with the Bedrock key, region
                            and budget above.
LiteLLM reads the model ids and keys itself from the environment.
"""
import os, re, sys

KIT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIRECT = {"anthropic": "ANTHROPIC_API_KEY", "openai": "OPENAI_API_KEY", "bedrock": "AWS_BEARER_TOKEN_BEDROCK"}
# Providers with a provider-wide daily budget next to OpenRouter's. Not OpenAI: the worker also counts as "openai".
PROVIDER_BUDGETS = ("anthropic", "bedrock")
ZDR = "      extra_body:\n        provider: {zdr: true, data_collection: deny}\n"
FALLBACK_RULE = ', {"colab-qwen": ["colab-qwen-fallback"]}'


def env():
    out = {}
    for line in open(os.path.join(KIT, ".env")):
        if "=" in line and not line.lstrip().startswith("#"):
            k, v = line.rstrip("\n").split("=", 1)
            out[k] = v.strip()
    return out


def tracing(t, e):
    """./rvkit tracing on (#51): LiteLLM exports a span per model call over OTLP, without messages."""
    if (e.get("RV_TRACING") or "off").lower() not in ("on", "1", "true", "yes"):
        return t
    t, n = re.subn(r'callbacks: \["rv_events.handler"\]', 'callbacks: ["rv_events.handler", "otel"]\n'
                   '  # a model call can carry client data, and LiteLLM can\'t apply the Client data rule per engagement:\n'
                   '  # its spans never carry messages\n'
                   '  turn_off_message_logging: true', t)
    if n != 1:
        sys.exit("litellm/config.yaml: the callbacks line was not found")
    return t


def main():
    t = render(open(os.path.join(KIT, "litellm", "config.yaml")).read(), env())
    out = os.path.join(KIT, ".rvkit", "litellm.yaml")
    os.makedirs(os.path.join(KIT, ".rvkit", "events"), exist_ok=True)  # model-problem log (litellm/rv_events.py)
    with open(out + ".tmp", "w") as f:
        f.write("# GENERATED by ./rvkit from litellm/config.yaml and .env. Edit those, not this file.\n" + t)
    os.replace(out + ".tmp", out)


def render(t, e):
    """The config the container reads: the template t with the .env settings e applied."""
    budget = e.get("OPENROUTER_DAILY_BUDGET") or "20"
    if not re.fullmatch(r"[0-9]+(\.[0-9]+)?", budget):
        sys.exit(f"OPENROUTER_DAILY_BUDGET in .env must be a number of USD, not {budget!r}")
    t, n = re.subn(r"(openrouter: \{budget_limit: )[0-9.]+", r"\g<1>" + budget, t)
    if n != 1:
        sys.exit("litellm/config.yaml: the provider_budget_config line was not found")
    if t.count(FALLBACK_RULE) != 2:
        sys.exit("litellm/config.yaml: expected the colab-qwen fallback rule in fallbacks and content_policy_fallbacks")
    if e.get("WORKER_FALLBACK", "off").lower() != "on":
        t = t.replace(FALLBACK_RULE, "")
    if not e.get("VALIDATOR_MODEL"):   # an older .env: the validator uses the planner's fallback model
        e["VALIDATOR_MODEL"] = e.get("PLANNER_FALLBACK_MODEL") or ""
        t = t.replace("model: os.environ/VALIDATOR_MODEL", "model: os.environ/PLANNER_FALLBACK_MODEL")
    t = tracing(t, e)
    t, used = planners(t, e, budget)
    t, worker_prov = worker(t, e)
    used |= worker_prov
    if "bedrock" in used and not e.get("AWS_REGION_NAME"):
        print("warning: a model is on Amazon Bedrock but AWS_REGION_NAME is empty in .env (e.g. us-east-1)", file=sys.stderr)
    for prov in PROVIDER_BUDGETS:
        if prov in used:
            t = provider_budget(t, prov, budget)
    return t


def provider_budget(t, prov, budget):
    """Add a daily provider budget next to OpenRouter's (once)."""
    if re.search(r"\n\s+%s: \{budget_limit: " % prov, t):
        return t
    return re.sub(r"(\n(\s+)openrouter: \{budget_limit: [0-9.]+, time_period: 1d\}\n)",
                  r"\1\2" + prov + ": {budget_limit: " + budget + ", time_period: 1d}\n", t, count=1)


def worker(t, e):
    """A hosted worker without a GPU: the colab-qwen and private-llm aliases use the provider's key instead of
    WORKER_API_BASE / WORKER_API_KEY. OpenRouter: zero-data-retention providers, like every other OpenRouter call.
    Bedrock: the Bedrock API key (AWS_BEARER_TOKEN_BEDROCK); LiteLLM reads the region from AWS_REGION_NAME."""
    mid = e.get("WORKER_MODEL_ID") or ""
    prov = mid.split("/", 1)[0] if "/" in mid else ""
    if prov not in ("openrouter", "bedrock"):
        return t, set()
    key = "OPENROUTER_API_KEY" if prov == "openrouter" else DIRECT["bedrock"]
    if not e.get(key):
        print(f"warning: WORKER_MODEL_ID is {mid} but {key} is empty in .env", file=sys.stderr)
    for name in ("colab-qwen", "private-llm"):
        m = re.search(r"  - model_name: %s\n(?:    .*\n)+" % re.escape(name), t)
        old = "      api_base: os.environ/WORKER_API_BASE\n      api_key: os.environ/WORKER_API_KEY\n"
        if not m or old not in m.group(0):
            sys.exit(f"litellm/config.yaml: the {name} entry is not in the expected form")
        block = m.group(0).replace(old, f"      api_key: os.environ/{key}\n") + (ZDR if prov == "openrouter" else "")
        t = t[:m.start()] + block + t[m.end():]
    return t, {prov}


def planners(t, e, budget):
    """Point planner / planner-fallback / validator at a direct provider when their model id says so."""
    used = set()
    for name, var in (("planner", "PLANNER_MODEL"), ("planner-fallback", "PLANNER_FALLBACK_MODEL"),
                      ("validator", "VALIDATOR_MODEL")):
        prov = (e.get(var) or "openrouter/").split("/", 1)[0]
        if prov == "openrouter":
            continue
        if prov not in DIRECT:
            sys.exit(f"{var} in .env must start with openrouter/, anthropic/, openai/ or bedrock/, not {e.get(var)!r}")
        if not e.get(DIRECT[prov]):
            print(f"warning: {var} is {e[var]} but {DIRECT[prov]} is empty in .env (./rvkit planner --direct asks for it)",
                  file=sys.stderr)
        m = re.search(r"  - model_name: %s\n(?:    .*\n)+" % re.escape(name), t)
        if not m or "os.environ/OPENROUTER_API_KEY" not in m.group(0) or ZDR not in m.group(0):
            sys.exit(f"litellm/config.yaml: the {name} entry is not in the expected form")
        block = m.group(0).replace("os.environ/OPENROUTER_API_KEY", "os.environ/" + DIRECT[prov]).replace(ZDR, "")
        if prov == "openai":
            block += f"      max_budget: {budget}\n      budget_duration: 1d\n"
        t = t[:m.start()] + block + t[m.end():]
        used.add(prov)
    return t, used


if __name__ == "__main__":
    main()
