"""Render the LiteLLM config the container reads (.rvkit/litellm.yaml) from the tracked template
(litellm/config.yaml) and the user's settings in .env. Run by ./rvkit before LiteLLM starts.

Settings (.env):
  OPENROUTER_DAILY_BUDGET   USD per day for all OpenRouter calls (planner, and the worker fallback when on). Default 20
  WORKER_FALLBACK           on | off (default off). on: while the worker endpoint is down, worker calls go to
                            WORKER_FALLBACK_MODEL on OpenRouter, which then sees tool output and client code
Planner models (PLANNER_MODEL, PLANNER_FALLBACK_MODEL) are read by LiteLLM itself from the environment.
"""
import os, re, sys

KIT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FALLBACK_RULE = ', {"colab-qwen": ["colab-qwen-fallback"]}'


def env():
    out = {}
    for line in open(os.path.join(KIT, ".env")):
        if "=" in line and not line.lstrip().startswith("#"):
            k, v = line.rstrip("\n").split("=", 1)
            out[k] = v.strip()
    return out


def main():
    e = env()
    t = open(os.path.join(KIT, "litellm", "config.yaml")).read()
    budget = e.get("OPENROUTER_DAILY_BUDGET") or "20"
    if not re.fullmatch(r"[0-9]+(\.[0-9]+)?", budget):
        sys.exit(f"OPENROUTER_DAILY_BUDGET in .env must be a number of USD, not {budget!r}")
    t, n = re.subn(r"(openrouter: \{budget_limit: )[0-9.]+", r"\g<1>" + budget, t)
    if n != 1:
        sys.exit("litellm/config.yaml: the provider_budget_config line was not found")
    if t.count(FALLBACK_RULE) != 2:
        sys.exit("litellm/config.yaml: expected the colab-qwen fallback rule in fallbacks and content_policy_fallbacks")
    if e.get("WORKER_FALLBACK", "off").lower() != "on":
        t = t.replace(FALLBACK_RULE, "")
    out = os.path.join(KIT, ".rvkit", "litellm.yaml")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out + ".tmp", "w") as f:
        f.write("# GENERATED by ./rvkit from litellm/config.yaml and .env. Edit those, not this file.\n" + t)
    os.replace(out + ".tmp", out)


if __name__ == "__main__":
    main()
