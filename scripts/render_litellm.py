"""Render the LiteLLM config the container reads (.rvkit/litellm.yaml) from the tracked template
(litellm/config.yaml) and the user's settings in .env. Run by ./rvkit before LiteLLM starts.

Settings (.env):
  OPENROUTER_DAILY_BUDGET   USD per day for all OpenRouter calls (planner, and the worker fallback when on). Default 20
  WORKER_FALLBACK           on | off (default off). on: while the worker endpoint is down, worker calls go to
                            WORKER_FALLBACK_MODEL on OpenRouter, which then sees tool output and client code
  PLANNER_MODEL, PLANNER_FALLBACK_MODEL
                            openrouter/<id> (default): OpenRouter key, zero-data-retention providers only.
                            anthropic/<id> or openai/<id>: that provider's API directly, with ANTHROPIC_API_KEY or
                            OPENAI_API_KEY. The daily budget then also caps that provider (Anthropic: provider budget;
                            OpenAI: a budget on each planner model, because the worker also counts as provider "openai").
LiteLLM reads the model ids and keys itself from the environment.
"""
import os, re, sys

KIT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIRECT = {"anthropic": "ANTHROPIC_API_KEY", "openai": "OPENAI_API_KEY"}
ZDR = "      extra_body:\n        provider: {zdr: true, data_collection: deny}\n"
FALLBACK_RULE = ', {"colab-qwen": ["colab-qwen-fallback"]}'


def env():
    out = {}
    for line in open(os.path.join(KIT, ".env")):
        if "=" in line and not line.lstrip().startswith("#"):
            k, v = line.rstrip("\n").split("=", 1)
            out[k] = v.strip()
    return out


def main():
    e = env()
    t = open(os.path.join(KIT, "litellm", "config.yaml")).read()
    budget = e.get("OPENROUTER_DAILY_BUDGET") or "20"
    if not re.fullmatch(r"[0-9]+(\.[0-9]+)?", budget):
        sys.exit(f"OPENROUTER_DAILY_BUDGET in .env must be a number of USD, not {budget!r}")
    t, n = re.subn(r"(openrouter: \{budget_limit: )[0-9.]+", r"\g<1>" + budget, t)
    if n != 1:
        sys.exit("litellm/config.yaml: the provider_budget_config line was not found")
    if t.count(FALLBACK_RULE) != 2:
        sys.exit("litellm/config.yaml: expected the colab-qwen fallback rule in fallbacks and content_policy_fallbacks")
    if e.get("WORKER_FALLBACK", "off").lower() != "on":
        t = t.replace(FALLBACK_RULE, "")
    t = planners(t, e, budget)
    out = os.path.join(KIT, ".rvkit", "litellm.yaml")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out + ".tmp", "w") as f:
        f.write("# GENERATED by ./rvkit from litellm/config.yaml and .env. Edit those, not this file.\n" + t)
    os.replace(out + ".tmp", out)


def planners(t, e, budget):
    """Point planner / planner-fallback at a direct provider when their model id says so."""
    used = set()
    for name, var in (("planner", "PLANNER_MODEL"), ("planner-fallback", "PLANNER_FALLBACK_MODEL")):
        prov = (e.get(var) or "openrouter/").split("/", 1)[0]
        if prov == "openrouter":
            continue
        if prov not in DIRECT:
            sys.exit(f"{var} in .env must start with openrouter/, anthropic/ or openai/, not {e.get(var)!r}")
        if not e.get(DIRECT[prov]):
            print(f"warning: {var} is {e[var]} but {DIRECT[prov]} is empty in .env (./rvkit planner --direct asks for it)",
                  file=sys.stderr)
        m = re.search(r"  - model_name: %s\n(?:    .*\n)+" % re.escape(name), t)
        if not m or "os.environ/OPENROUTER_API_KEY" not in m.group(0) or ZDR not in m.group(0):
            sys.exit(f"litellm/config.yaml: the {name} entry is not in the expected form")
        block = m.group(0).replace("os.environ/OPENROUTER_API_KEY", "os.environ/" + DIRECT[prov]).replace(ZDR, "")
        if prov == "openai":
            block += f"      max_budget: {budget}\n      budget_duration: 1d\n"
        t = t[:m.start()] + block + t[m.end():]
        used.add(prov)
    if "anthropic" in used:
        t = re.sub(r"(\n(\s+)openrouter: \{budget_limit: [0-9.]+, time_period: 1d\}\n)",
                   r"\1\2anthropic: {budget_limit: " + budget + ", time_period: 1d}\n", t, count=1)
    return t


if __name__ == "__main__":
    main()
