"""The improvement loop (epic #52, issue #50): error analysis, one proposal per cause, a judge with a held-out check,
and a changelog. Procedure: docs/improvement-loop.md.

  python3 evals/improve.py split                   the tuning and held-out benchmarks (evals/improvement/split.json)
  python3 evals/improve.py analyze [--label L] [--top N] [--sample K] [--out FILE]
                                                   the top causes on the tuning benchmarks, with K records of each
                                                   to read (--out: a worksheet to write notes in)
  python3 evals/improve.py propose <cause> --kind <kind> --file <path> --change "<what changes>"
                                   [--targets <run>,<run>...] [--read N]
                                                   record a proposal: one change for one cause
  python3 evals/improve.py list                    the proposals and their verdicts
  python3 evals/improve.py judge <id> --baseline <label> --candidate <label> [--write]
                                                   keep or drop it; --write saves the verdict and the changelog
  python3 evals/improve.py changelog               write docs/harness-changelog.md from the judged proposals
  (or ./rvkit bench --improve ...)

A proposal changes one thing (kind: prompt, tool-description, playbook, error-message, other) for one failure cause
(a cause from evals/failures.py; a prefix such as missed/seen-in-output covers its sub-causes). The judge reads two
labelled sets of benchmark runs (./rvkit bench all --repeat N --label <label>): the baseline without the change and
the candidate with it. It keeps the change only when all three hold:

  the cause shrinks      on the tuning benchmarks, its records per run fall by more than one standard error of the
                         difference (with fewer than 2 runs on a side there is no spread: incomplete)
  held-out holds         on the held-out benchmarks, the paired comparison of strict recall (bench_stats.compare)
                         has a 95% interval that isn't wholly below zero
  safety holds           no safety cause (policy/, clean-control/) has more records per run, on any benchmark

Nothing here calls a model or the stack: every figure comes from saved results and evals/results/bench/failures.jsonl.
"""
import collections, datetime, json, math, os, random, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bench_stats as stats  # noqa: E402
import failures  # noqa: E402

KIT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HERE = os.path.join(KIT, "evals", "improvement")
SPLIT = os.path.join(HERE, "split.json")
PROPOSALS = os.path.join(HERE, "proposals")
CHANGELOG = os.path.join(KIT, "docs", "harness-changelog.md")
KINDS = ("prompt", "tool-description", "playbook", "error-message", "other")
MARK = "<!-- generated by evals/improve.py changelog: edit the proposals, not this list -->"


def split(path=None):
    return json.load(open(path or SPLIT))


def matches(cause, prefix):
    """A cause, or one under it: tool/x/refused covers tool/x/refused/... and tool/x/refused: <reason>."""
    p = prefix.rstrip("/")
    return cause == prefix or cause.startswith(p + "/") or cause.startswith(p + ":")


# ---------------------------------------------------------------- error analysis
def top_causes(rows, benchmarks, top=5):
    """The most widespread causes on the given benchmarks (failures.groups order: runs affected, then count)."""
    rows = [r for r in rows if r.get("benchmark") in benchmarks]
    return failures.groups(rows)[:top], rows


def sample(rows, cause, k=10, seed=0):
    """k records of a cause, spread over runs: a fixed seed, so a worksheet can be written again."""
    hit = [r for r in rows if r["kind"] != failures.SUMMARY and matches(r["cause"], cause)]
    by_run = collections.defaultdict(list)
    for r in hit:
        by_run[r["run"]].append(r)
    rnd = random.Random(seed)
    for v in by_run.values():
        rnd.shuffle(v)
    out, runs = [], sorted(by_run)
    while len(out) < k and any(by_run[x] for x in runs):   # one per run in turn: no run dominates the reading
        for x in runs:
            if by_run[x] and len(out) < k:
                out.append(by_run[x].pop())
    return out


def worksheet(groups, rows, k, out=print):
    out("# Error analysis worksheet\n")
    out("Read each record with `./rvkit bench --failures --show <cause>` and the run's conversation.json, and write "
        "what actually went wrong. One proposal per cause comes from these notes, not from the counts alone.\n")
    for g in groups:
        out(f"## {g['cause']}: {g['count']} records in {len(g['runs'])} runs\n")
        for r in sample(rows, g["cause"], k):
            d = "; ".join(f"{a}: {b if isinstance(b, str) else json.dumps(b)}" for a, b in (r.get("detail") or {}).items())
            out(f"- [ ] {r['run']} {r.get('subject') or ''}" + (f"  ({d[:300]})" if d else ""))
            out("  What happened: ")
        out("")


# ---------------------------------------------------------------- proposals
def _path(pid):
    if not re.fullmatch(r"P-\d{3,}", pid or ""):
        raise SystemExit(f"not a proposal id: {pid!r} (P-001, P-002, ...)")
    return os.path.join(PROPOSALS, pid + ".json")


def proposals():
    if not os.path.isdir(PROPOSALS):
        return []
    return [json.load(open(os.path.join(PROPOSALS, f))) for f in sorted(os.listdir(PROPOSALS)) if f.endswith(".json")]


def propose(cause, kind, file, change, targets=(), read=None, now=None):
    if kind not in KINDS:
        raise SystemExit(f"--kind is one of {', '.join(KINDS)}")
    if not change or not file:
        raise SystemExit("a proposal needs --file (what it edits) and --change (what it changes)")
    os.makedirs(PROPOSALS, exist_ok=True)
    n = max([int(p["id"][2:]) for p in proposals()] + [0]) + 1
    p = {"id": f"P-{n:03d}", "created": (now or datetime.datetime.now(datetime.timezone.utc)).strftime("%Y-%m-%d"),
         "cause": cause, "kind": kind, "file": file, "change": change, "targets": list(targets),
         "read": read, "status": "proposed", "judgement": None}
    save(p)
    return p


def save(p):
    with open(_path(p["id"]), "w") as f:
        json.dump(p, f, indent=1)
        f.write("\n")


# ---------------------------------------------------------------- the judge
def per_run(rows, runs, prefix):
    """Records of a cause per run, for each run (0 for a run without any)."""
    names = [r["_file"][:-5] for r in runs]
    c = collections.Counter()
    for r in rows:
        if r["kind"] != failures.SUMMARY and matches(r["cause"], prefix):
            c[r["run"]] += r.get("n") or 1
    return [c[n] for n in names]


def _rate(xs):
    m, se, n = stats.mean_se(xs)
    return {"mean": stats._r(m), "se": stats._r(se), "runs": n}


def judge(cause, base, cand, rows, sp):
    """The verdict on one proposal. base and cand: saved results (with _file) of the baseline and candidate labels;
    rows: failure records. Returns a JSON-able dict with verdict kept, dropped or incomplete, and the reasons."""
    tune, held = set(sp["tuning"]), set(sp["held_out"])
    bt, ct = [r for r in base if r["benchmark"] in tune], [r for r in cand if r["benchmark"] in tune]
    bh, ch = [r for r in base if r["benchmark"] in held], [r for r in cand if r["benchmark"] in held]
    out = {"cause": cause, "reasons": [], "missing": []}

    # the targeted cause, on the tuning benchmarks the two sets share
    shared = sorted({r["benchmark"] for r in bt} & {r["benchmark"] for r in ct})
    bt, ct = [r for r in bt if r["benchmark"] in shared], [r for r in ct if r["benchmark"] in shared]
    before, after = _rate(per_run(rows, bt, cause)), _rate(per_run(rows, ct, cause))
    out["tuning"] = {"benchmarks": shared, "before": before, "after": after}
    if before["runs"] < 2 or after["runs"] < 2:
        out["missing"].append("2 or more runs on each side on the tuning benchmarks")
        shrinks = None
    else:
        sd = math.hypot(before["se"] or 0, after["se"] or 0)
        drop = before["mean"] - after["mean"]
        shrinks = drop > sd if sd else drop > 0
        out["tuning"]["drop"], out["tuning"]["se"] = stats._r(drop), stats._r(sd)
        out["reasons"].append(f"{cause}: {before['mean']} → {after['mean']} records per run (SE of the difference "
                              f"{stats._r(sd)}): " + ("shrank" if shrinks else "didn't shrink beyond the noise"))

    # held-out: strict recall, paired by expected item
    c = stats.compare(bh, ch)
    out["held_out"] = c
    if not c["items"]:
        out["missing"].append("runs of the held-out benchmarks under both labels")
        holds = None
    elif not c.get("ci95"):
        out["missing"].append("a spread on the held-out benchmarks (more items or more runs)")
        holds = None
    else:
        holds = not (c["ci95"] and c["ci95"][1] < 0)
        out["reasons"].append(f"held-out strict recall per item {c['diff']:+.3f}, 95% CI {c['ci95']}: "
                              + ("holds" if holds else "fell beyond the spread"))

    # safety, on every benchmark either set ran
    worse = []
    for prefix in sp.get("safety_causes", []):
        b, a = _rate(per_run(rows, base, prefix)), _rate(per_run(rows, cand, prefix))
        if b["runs"] and a["runs"] and (a["mean"] or 0) > (b["mean"] or 0):
            worse.append(f"{prefix} {b['mean']} → {a['mean']} per run")
    out["safety"] = worse
    if worse:
        out["reasons"].append("safety causes rose: " + "; ".join(worse))

    if worse or shrinks is False or holds is False:
        out["verdict"] = "dropped"
    elif shrinks and holds:
        out["verdict"] = "kept"
    else:
        out["verdict"] = "incomplete"
    return out


# ---------------------------------------------------------------- changelog
def changelog(props, out_path=None):
    judged = [p for p in props if p.get("status") in ("kept", "dropped") and p.get("judgement")]
    kept = sorted((p for p in judged if p["status"] == "kept"), key=lambda p: p["judgement"].get("at") or "",
                  reverse=True)
    dropped = sorted((p for p in judged if p["status"] == "dropped"), key=lambda p: p["judgement"].get("at") or "",
                     reverse=True)
    lines = ["# Harness changelog", "",
             "Changes to prompts, tool descriptions, playbooks and error messages that the improvement loop kept, each "
             "with the numbers that kept it, and the ones it dropped. How a change gets here: "
             "[improvement-loop.md](improvement-loop.md).", "", MARK, ""]
    if not judged:
        lines += ["No proposal has been judged yet.", ""]
    for p in kept:
        j = p["judgement"]
        t, h = j.get("tuning") or {}, j.get("held_out") or {}
        lines += [f"## {p['id']} ({j.get('at', '')[:10]}): {p['change']}", "",
                  f"- Cause: `{p['cause']}`; {p['kind']} in `{p['file']}`"
                  + (f"; from {p['read']} records read" if p.get("read") else ""),
                  f"- Tuning ({', '.join(t.get('benchmarks') or [])}): {t['before']['mean']} → {t['after']['mean']} "
                  f"records per run ({t['before']['runs']} and {t['after']['runs']} runs, SE of the difference "
                  f"{t.get('se')})",
                  f"- Held-out strict recall per item: {h.get('diff'):+.3f}, 95% CI {h.get('ci95')} over "
                  f"{h.get('items')} items",
                  f"- Runs: baseline `{j['baseline']}`, candidate `{j['candidate']}`"
                  + (f"; commit {p['commit']}" if p.get("commit") else ""), ""]
    if dropped:
        lines += ["## Tried and dropped", "", "| Proposal | Cause | Change | Why |", "|---|---|---|---|"]
        for p in dropped:
            why = "; ".join(p["judgement"].get("reasons") or []).replace("|", "/")
            lines.append(f"| {p['id']} | `{p['cause']}` | {p['change'].replace('|', '/')} | {why} |")
        lines.append("")
    text = "\n".join(lines)
    with open(out_path or CHANGELOG, "w") as f:
        f.write(text)
    return text


# ---------------------------------------------------------------- command line
def _opt(argv, name, default=None):
    return argv[argv.index(name) + 1] if name in argv and argv.index(name) + 1 < len(argv) else default


def main(argv):
    if not argv or argv[0] in ("-h", "--help"):
        print(__doc__)
        return 0
    cmd, sp = argv[0], split()
    if cmd == "split":
        print("tuning:   " + ", ".join(sp["tuning"]))
        print("held-out: " + ", ".join(sp["held_out"]))
        print("safety causes (must not rise anywhere): " + ", ".join(sp.get("safety_causes", [])))
        return 0
    if cmd == "analyze":
        import run_benchmark
        rows = failures.load()
        label = _opt(argv, "--label")
        if label:
            names = {r["_file"][:-5] for r in run_benchmark.load_results(label=label)}
            rows = [r for r in rows if r["run"] in names]
        gs, rows = top_causes(rows, set(sp["tuning"]), int(_opt(argv, "--top", 5)))
        if not gs:
            print("No failure records on the tuning benchmarks" + (f" labelled {label!r}" if label else "")
                  + ": run them first (./rvkit bench <name> --repeat 3 --label <label>).")
            return 1
        k = int(_opt(argv, "--sample", 10))
        if _opt(argv, "--out"):
            with open(_opt(argv, "--out"), "w") as f:
                worksheet(gs, rows, k, out=lambda s: f.write(s + "\n"))
            print(f"worksheet: {_opt(argv, '--out')} ({len(gs)} causes, up to {k} records each)")
        else:
            worksheet(gs, rows, k)
        return 0
    if cmd == "propose":
        if len(argv) < 2 or argv[1].startswith("--"):
            print("usage: propose <cause> --kind <kind> --file <path> --change \"...\" [--targets r1,r2] [--read N]")
            return 2
        p = propose(argv[1], _opt(argv, "--kind"), _opt(argv, "--file"), _opt(argv, "--change"),
                    [t for t in (_opt(argv, "--targets") or "").split(",") if t],
                    int(_opt(argv, "--read")) if _opt(argv, "--read") else None)
        print(f"{p['id']}: {p['cause']} ({p['kind']} in {p['file']}). Run the baseline and the candidate, then: "
              f"python3 evals/improve.py judge {p['id']} --baseline <label> --candidate <label> --write")
        return 0
    if cmd == "list":
        ps = proposals()
        if not ps:
            print("No proposals yet: python3 evals/improve.py propose <cause> ...")
        for p in ps:
            print(f"{p['id']}  {p['status']:10} {p['cause']}\n        {p['change'][:100]}")
        return 0
    if cmd == "judge":
        import run_benchmark
        b, c = _opt(argv, "--baseline"), _opt(argv, "--candidate")
        if len(argv) < 2 or not b or not c:
            print("usage: judge <id> --baseline <label> --candidate <label> [--write]")
            return 2
        p = json.load(open(_path(argv[1])))
        base, cand = run_benchmark.load_results(label=b), run_benchmark.load_results(label=c)
        rows = failures.load()
        recorded = {r["run"] for r in rows if r["kind"] == failures.SUMMARY}
        for r in base + cand:   # a run whose failures weren't recorded counts as none: record it first
            if r["_file"][:-5] not in recorded:
                failures.record(os.path.join(run_benchmark.OUT, r["_file"]))
        rows = failures.load()
        j = judge(p["cause"], base, cand, rows, sp)
        j.update(baseline=b, candidate=c, at=datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"))
        print(f"{p['id']} {p['cause']}: {j['verdict'].upper()}")
        for r in j["reasons"]:
            print("  " + r)
        for m in j["missing"]:
            print("  missing: " + m)
        if "--write" in argv:
            p["judgement"] = j
            if j["verdict"] in ("kept", "dropped"):
                p["status"] = j["verdict"]
            save(p)
            changelog(proposals())
            print(f"  saved to {os.path.relpath(_path(p['id']), KIT)} and docs/harness-changelog.md")
        return 0 if j["verdict"] != "incomplete" else 1
    if cmd == "changelog":
        changelog(proposals())
        print("docs/harness-changelog.md written")
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
